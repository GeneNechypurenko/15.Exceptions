#include <iostream>
#include <string>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                          Виняткові ситуації. Ключові слова try, throw, catch
==========================================================================================================================================

  ВИНЯТКОВА СИТУАЦІЯ (виняток, exception) — помилка під час виконання, через яку функція не може виконати свою роботу:
  некоректні дані, немає оцінок для підрахунку середнього, не відкрився файл, не вистачило пам'яті.

  Чому не код повернення (false, -1): його легко проігнорувати, він змішується з результатом функції,
  а конструктор узагалі нічого не повертає. Виняток проігнорувати не можна.

  Типи винятків:
  - СИНХРОННІ — програма кидає їх сама через throw. Механізм винятків C++ працює лише з ними.
  - АСИНХРОННІ (апаратні) — ділення цілого на 0, звернення за nullptr, вихід за межі масиву через [].
    Це НЕ винятки C++: try їх не ловить. Такі умови перевіряють заздалегідь і кидають виняток самі.

  THROW — оператор, що кидає (генерує) виняток: створює значення-виняток будь-якого типу і негайно перериває
  виконання поточного коду.
  TRY — блок коду, у якому може виникнути виняток. Виняток, кинутий усередині try (або в будь-якій функції,
  викликаній з нього), передається в catch цієї конструкції.
  CATCH — блок-обробник винятку. У дужках вказують тип винятку, який він обробляє; тіло виконується,
  лише якщо кинуто виняток саме цього типу.
  КОНСТРУКЦІЯ try/catch — блок try, за яким одразу йдуть один або кілька блоків catch.
  Між try і catch не може бути іншого коду; try без жодного catch — помилка компіляції.

      try                                    // код, у якому може виникнути виняток
      {
          throw значення;                    // кинути виняток: значення будь-якого типу
      }
      catch (int code)                       // обробник винятків типу int
      {
      }
      catch (const char* message)            // обробник винятків типу const char*
      {
      }
      catch (...)                            // обробник БУДЬ-ЯКОГО винятку; завжди останній
      {
      }

  Як це працює:
    1) throw негайно перериває try: решта коду в ньому не виконується;
    2) catch перевіряються згори вниз, спрацьовує ПЕРШИЙ, тип якого збігся з типом винятку;
    3) далі програма йде з рядка ПІСЛЯ останнього catch, назад у try не повертається.
  Типи порівнюються суворо: catch (double) не спіймає throw 5 (int).

  НЕОБРОБЛЕНИЙ ВИНЯТОК — виняток, для якого не знайшлося відповідного catch. Тоді викликається terminate(),
  і програма аварійно завершується.

  terminate() — стандартна функція, яку C++ викликає АВТОМАТИЧНО, коли продовжити обробку винятків неможливо:
  - виняток ніхто не спіймав;
  - під час розкрутки стека (тема наступного блоку) вилетів ще один виняток;
  - функція, позначена noexcept, кинула виняток.
  За замовчуванням terminate() викликає abort(): програма миттєво зупиняється без нормального завершення,
  деструктори об'єктів можуть не викликатися. У Visual Studio з'являється вікно «abort() has been called».
  Викликати terminate() самому не потрібно — це «аварійний вимикач» мови.

*/

class Student
{
private:
    string name;
    double gradeSum;
    int gradeCount;

public:
    Student(const string& name) : name(name), gradeSum(0), gradeCount(0)
    {}

    void addGrade(int grade)
    {
        if (grade < 1 || grade > 12)
        {
            throw grade;                      // тип винятку — int: кидаємо саму помилкову оцінку
        }
        gradeSum += grade;
        gradeCount++;
    }

    double getAverage() const
    {
        if (gradeCount == 0)
        {
            throw "Немає жодної оцінки";      // тип винятку — const char*: правильного числа повернути неможливо
        }
        return gradeSum / gradeCount;
    }
};

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Student olena("Олена Коваль");

    cout << "1. try / throw / catch" << endl;
    try
    {
        olena.addGrade(11);
        olena.addGrade(15);                   // throw 15 — решта блоку try пропускається
        cout << "Цей рядок не виконається" << endl;
    }
    catch (int grade)                         // тип int збігся з типом кинутого значення
    {
        cout << "Помилка: оцінки " << grade << " не існує" << endl;
    }
    cout << "Програма працює далі" << endl;

    cout << endl << "2. Кілька catch: спрацьовує той, чий тип збігся" << endl;
    Student marko("Марко Бондар");
    try
    {
        double average = marko.getAverage();  // оцінок немає — throw const char*
        cout << "Середній бал: " << average << endl;
    }
    catch (int grade)                         // пропускається: тип не той
    {
        cout << "Неправильна оцінка: " << grade << endl;
    }
    catch (const char* message)               // спрацьовує
    {
        cout << "Помилка: " << message << endl;
    }

    cout << endl << "3. catch (...) — для будь-якого винятку" << endl;
    try
    {
        marko.addGrade(0);                    // кидається int
    }
    catch (const char* message)
    {
        cout << "Помилка: " << message << endl;
    }
    catch (...)                               // int не збігся з const char*, тому спрацював цей
    {
        cout << "Невідома помилка" << endl;
    }

    cout << endl << "4. Необроблений виняток" << endl;
    // marko.addGrade(20);                    // без try: terminate() — вікно «abort() has been called»
    cout << "Розкоментуйте рядок вище і запустіть програму" << endl;

    return 0;
}

/*
==========================================================================================================================================
                                                  ІНСАЙТИ / ЛАЙФХАКИ / BEST PRACTICES
==========================================================================================================================================

  1. Винятки — для ВИНЯТКОВИХ ситуацій. Звичайний сценарій (пошук нічого не знайшов, неправильний пароль)
     обробляють if і поверненням bool.

  2. Кидати int чи const char* так, як тут, роблять лише в навчальних прикладах. У реальному коді кидають об'єкти
     класів-винятків — це тема наступних блоків.

  3. catch (...) не дає доступу до самого винятку. Порожній catch (...) {}, що «глушить» усі помилки, — погана практика:
     програма мовчки працює з некоректними даними.

==========================================================================================================================================
                                                              ПРАКТИКА
==========================================================================================================================================

  Усі завдання цього уроку — про один клас Wallet (гаманець героя). Він росте від блоку до блоку.
  Початковий код — скопіюйте собі:

      class Wallet
      {
      private:
          int gold;

      public:
          explicit Wallet(int gold) : gold(gold)
          {}

          void spend(int amount)
          {
              gold -= amount;
          }

          int getGold() const
          {
              return gold;
          }
      };

  Завдання 1.
    - У spend додайте перевірки ПЕРЕД зменшенням gold:
        якщо amount <= 0 — throw "Сума має бути додатною";
        якщо amount > gold — throw (amount - gold); (int: скільки золота бракує).
  У main:
    - створіть гаманець на 100 золота;
    - в одному try: spend(30), spend(100); два catch: int — «Бракує <n> золота», const char* — вивести повідомлення;
    - після catch виведіть залишок золота;
    - в окремому try викличте spend(-5) і спіймайте його через catch (...).
*/
