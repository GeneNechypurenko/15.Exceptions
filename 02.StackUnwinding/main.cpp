#include <iostream>
#include <string>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                Винятки та функції. Розкрутка стека
==========================================================================================================================================

  throw можна писати в будь-якій функції, методі, конструкторі. try/catch пишуть там, де ЗНАЮТЬ, що робити з помилкою.
  Якщо у функції немає відповідного catch, виняток виходить з неї до функції, яка її викликала, і далі — аж до main.

  Виняток з КОНСТРУКТОРА означає: об'єкт НЕ створено, і його деструктор НЕ викликається.
  Це єдиний спосіб повідомити про помилку з конструктора — він нічого не повертає.

  РОЗКРУТКА СТЕКА (stack unwinding) — коли виняток виходить з блоку чи функції, усі ЛОКАЛЬНІ об'єкти, що в ній
  встигли створитися, знищуються автоматично: викликаються їхні деструктори, у порядку, зворотному до створення.
  Тому деструктор звільняє ресурси і при звичайному виході з функції, і при винятку.
  Пам'ять, виділена через new і ще не звільнена через delete, при винятку витікає.

*/

class Student
{
private:
    string name;
    int age;

public:
    Student(const string& name, int age) : name(name), age(16)
    {
        setAge(age);                          // некоректний вік — виняток з конструктора, об'єкт не створиться
        cout << "  [створено Student: " << name << "]" << endl;
    }

    ~Student()
    {
        cout << "  [деструктор Student: " << name << "]" << endl;
    }

    void setAge(int age)
    {
        if (age < 16 || age > 100)
        {
            throw "Вік має бути від 16 до 100";
        }
        this->age = age;
    }
};

// Функція сама помилку не обробляє: виняток виходить з неї в main
void enrollGroup()
{
    Student first("Андрій Шевчук", 19);
    Student second("Софія Ткач", 35);
    Student third("Іван Мельник", 12);       // throw: third не створено, second і first знищуються
    cout << "Цей рядок не виконається" << endl;
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    cout << "1. Виняток з конструктора" << endl;
    try
    {
        Student ivan("Іван Мельник", 12);
        cout << "Цей рядок не виконається" << endl;
    }
    catch (const char* message)
    {
        cout << "Студента не створено: " << message << endl;   // деструктор ivan НЕ викликався
    }

    cout << endl << "2. Розкрутка стека: виняток виходить з функції" << endl;
    try
    {
        enrollGroup();
    }
    catch (const char* message)
    {
        // До цього рядка вже спрацювали деструктори second і first — у зворотному порядку
        cout << "main: " << message << endl;
    }

    return 0;
}

