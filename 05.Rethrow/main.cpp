#include <iostream>
#include <string>
#include <stdexcept>
#include <windows.h>

using namespace std;

/*
==========================================================================================================================================
                                                     Повторна генерація винятку
==========================================================================================================================================

  throw; (без значення) всередині catch кидає ДАЛІ той самий виняток, який щойно спіймали.

  Навіщо: функція знає лише частину ситуації. Вона обробляє помилку частково (записує в журнал, повідомляє,
  скасовує свою дію) і передає її вище — тому, хто вирішує, що робити далі.
      catch (const invalid_argument& e)
      {
          cout << "[журнал] ...";
          throw;                          // той самий об'єкт, без копіювання і без втрати типу
      }

  throw e; — це НЕ повторна генерація: кидається КОПІЯ за типом посилання. Якщо в e лежав нащадок,
  у копії залишиться лише «частина» базового класу (зрізання).
  throw; поза catch — помилка: виняток, який нема кому передати, призводить до terminate().

*/


class Student
{
private:
    string name;
    double gradeSum;
    int gradeCount;

public:
    Student(const string& name) : name(name), gradeSum(0), gradeCount(0)
    {}

    void addGrade(int grade)
    {
        if (grade < 1 || grade > 12)
        {
            throw invalid_argument("Оцінки " + to_string(grade) + " не існує (шкала 1-12)");
        }
        gradeSum += grade;
        gradeCount++;
    }

    double getAverage() const
    {
        return gradeCount == 0 ? 0 : gradeSum / gradeCount;
    }
};

// Вносить оцінки з масиву. Помилку обробляє частково (журнал) і передає далі
void loadGrades(Student& student, const int grades[], int count)
{
    int loaded = 0;
    try
    {
        for (int i = 0; i < count; i++)
        {
            student.addGrade(grades[i]);
            loaded++;
        }
    }
    catch (const invalid_argument& e)
    {
        cout << "  [журнал] внесено " << loaded << " з " << count << " оцінок" << endl;
        throw;                                // повторна генерація: той самий виняток іде в main
    }
}

int main()
{
    SetConsoleOutputCP(65001);
    SetConsoleCP(65001);

    Student marko("Марко Бондар");
    int grades[] = { 10, 11, 0, 12 };

    try
    {
        loadGrades(marko, grades, 4);
    }
    catch (const exception& e)                // main вирішує: повідомити і працювати далі
    {
        cout << "main: " << e.what() << endl;
    }
    cout << "Середній бал Марка: " << marko.getAverage() << endl;   // 10.5 — дві оцінки встигли внестися

    return 0;
}

